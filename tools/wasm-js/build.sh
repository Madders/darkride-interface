#!/bin/sh
# Builds darkride-js.wasm, the JavaScript guest: QuickJS-NG at a pinned version compiled with wasi-sdk as a
# static library, the shim (runtime.js) embedded, and darkride-js.c linked against both as a reactor module.
#
#   tools/wasm-js/build.sh            builds build/darkride-js.wasm
#   WASI_SDK=<dir> tools/wasm-js/build.sh
#
# The QuickJS-NG source archive is taken from $TIVOLI_DOWNLOADS/quickjs-ng-v<version>/ or
# ../downloads/quickjs-ng-v<version>/ beside the checkout when it is there, and from GitHub otherwise; its
# SHA-256 is checked either way. It is unpacked under build/, in a directory of its own, and patches/*.patch are
# applied to it in order (changes to QuickJS-NG for speed, each described at the top of its file). When the
# patches change, the source is unpacked and the library built again.
set -e
D=$(cd "$(dirname "$0")" && pwd)
WASI_SDK=${WASI_SDK:-$HOME/git/tivolicloud/wasi-sdk/wasi-sdk-34.0-arm64-macos}
QUICKJS_VERSION=0.17.0
QUICKJS_SHA256=559bc4c420475e55c7ab4510adbc562f55d7524d75e8e89d79ce4bb02f5687d9
ARCHIVE_NAME=quickjs-ng-v$QUICKJS_VERSION.tar.gz
OUT=$D/build
mkdir -p "$OUT"

[ -x "$WASI_SDK/bin/clang" ] || { echo "no wasi-sdk at $WASI_SDK (set WASI_SDK)" >&2; exit 1; }

# --- the QuickJS-NG source ----------------------------------------------------------------------------------
ARCHIVE=
for DIR in "$D/../../../downloads/quickjs-ng-v$QUICKJS_VERSION" "${TIVOLI_DOWNLOADS:-/nonexistent}/quickjs-ng-v$QUICKJS_VERSION"; do
    if [ -f "$DIR/$ARCHIVE_NAME" ]; then
        ARCHIVE="$DIR/$ARCHIVE_NAME"
        break
    fi
done
if [ -z "$ARCHIVE" ]; then
    mkdir -p "$OUT/downloads"
    ARCHIVE="$OUT/downloads/$ARCHIVE_NAME"
    if [ ! -f "$ARCHIVE" ]; then
        echo "fetching QuickJS-NG v$QUICKJS_VERSION"
        curl -sSL -o "$ARCHIVE" "https://github.com/quickjs-ng/quickjs/archive/refs/tags/v$QUICKJS_VERSION.tar.gz"
    fi
fi
ACTUAL=$(shasum -a 256 "$ARCHIVE" | cut -d' ' -f1)
[ "$ACTUAL" = "$QUICKJS_SHA256" ] || { echo "$ARCHIVE: SHA-256 $ACTUAL, expected $QUICKJS_SHA256" >&2; exit 1; }
SRC="$OUT/quickjs-$QUICKJS_VERSION"
PATCHES_ID=$(cat "$D"/patches/*.patch 2>/dev/null | shasum -a 256 | cut -d' ' -f1)
if [ ! -f "$SRC/quickjs.h" ] || [ "$(cat "$SRC/.patches" 2>/dev/null)" != "$PATCHES_ID" ]; then
    rm -rf "$SRC" "$OUT/quickjs-build"
    mkdir -p "$OUT/unpack"
    # -m: the files are dated now, so a build that compiles them (tests/wasm-speed) sees the change
    tar -xzmf "$ARCHIVE" -C "$OUT/unpack"
    mv "$OUT/unpack/quickjs-$QUICKJS_VERSION" "$SRC"
    rmdir "$OUT/unpack"
    for PATCH in "$D"/patches/*.patch; do
        [ -f "$PATCH" ] || continue
        patch -d "$SRC" -p1 -s < "$PATCH" || { echo "$PATCH does not apply" >&2; exit 1; }
    done
    echo "$PATCHES_ID" > "$SRC/.patches"
fi

# --- the library, with wasi-sdk's CMake toolchain ----------------------------------------------------------
LIB="$OUT/quickjs-build/libqjs.a"
if [ ! -f "$LIB" ]; then
    cmake -S "$SRC" -B "$OUT/quickjs-build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_TOOLCHAIN_FILE="$WASI_SDK/share/cmake/wasi-sdk-p1.cmake" \
        -DQJS_BUILD_LIBC=OFF -DQJS_ENABLE_INSTALL=OFF -DQJS_BUILD_EXAMPLES=OFF > "$OUT/quickjs-configure.log" 2>&1
    ninja -C "$OUT/quickjs-build" qjs > "$OUT/quickjs-build.log" 2>&1
fi

# --- the shim, embedded ------------------------------------------------------------------------------------------
python3 - "$D/runtime.js" "$OUT/runtime_js.h" <<'EOF'
import sys
source = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as out:
    out.write("/* generated by build.sh from runtime.js; do not edit */\n")
    out.write("#include <stddef.h>\n")
    out.write("static const unsigned char RUNTIME_JS[] = {\n")
    for i in range(0, len(source), 16):
        out.write("    " + ", ".join(str(b) for b in source[i:i + 16]) + ",\n")
    out.write("    0,\n")  # JS_Eval reads a terminating zero past the length
    out.write("};\n")
    out.write("static const size_t RUNTIME_JS_LENGTH = %d;\n" % len(source))
EOF

# --- the module -------------------------------------------------------------------------------------------------
"$WASI_SDK/bin/clang" --target=wasm32-wasip1 -O2 -std=c11 -Wall -Wextra -Wno-unused-parameter \
    -D_WASI_EMULATED_PROCESS_CLOCKS -D_WASI_EMULATED_SIGNAL \
    -I "$SRC" -I "$OUT" \
    -mexec-model=reactor \
    -Wl,--stack-first -Wl,-z,stack-size=8388608 -Wl,--strip-debug \
    "$D/darkride-js.c" "$LIB" -lm -lwasi-emulated-process-clocks -lwasi-emulated-signal \
    -o "$OUT/darkride-js.wasm"
ls -la "$OUT/darkride-js.wasm"
